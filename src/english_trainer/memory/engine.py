"""The Obsidian projection: a readable, linked view of learner state
(contract 0.6; roadmap 2.4).

The vault is FOR THE HUMAN. It is never a scoring source and never how an
agent restores state (the tutor briefing comes from the engine). Two zones:
``memory/`` is fully generated and overwritten -- hand edits are drift and
get flagged, then lost on rebuild; ``notes/`` belongs to the learner and the
engine neither writes nor reads it.

Pages are ORDINARY markdown, deterministic to the byte: stable ordering
everywhere and, deliberately, **no wall clock in any page** -- dates come
from events and schedules, so re-rendering unchanged state reproduces
identical bytes (canon 3). Every page carries frontmatter with
``generated: true``, its declared source (event-sourced learning state vs
SQLite-authoritative operational state -- the hybrid split of canon 5), and
``source_ids``, which makes drift checking mechanical.

``render_pages`` is a pure function from state to ``{relative_path: bytes}``;
``render``/``rebuild``/``check`` are the thin IO around it. Rebuild deletes
orphans (pages whose entity vanished); check re-renders in memory and
compares -- a mismatch is an error, never silently repaired (read-only
commands repair nothing).

Honest gaps, named: error pages wait for ``ERROR_OBSERVED`` (2.8); gate pages
wait for the gates module; the irregular-verbs overview waits for lexeme-form
aggregation.
"""

